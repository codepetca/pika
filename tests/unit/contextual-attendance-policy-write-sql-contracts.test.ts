/** Source contracts only: these tests do not execute PostgreSQL. */
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const sql = readFileSync('supabase/migrations/274_contextual_attendance_owner_policy_write.sql','utf8')
const rollback = readFileSync('scripts/check-contextual-attendance-policy-write.sql','utf8')
describe('contextual attendance owner policy write SQL source contract', () => {
  it('exposes one bounded service-only function without changing existing writers, roles or grants', () => {
    expect(sql.match(/create function /g)).toHaveLength(1)
    expect(sql).toContain('language plpgsql security definer')
    expect(sql).toContain("set search_path = ''")
    expect(sql).toContain("set lock_timeout = '1s'")
    expect(sql).toContain("set statement_timeout = '8s'")
    expect(sql).toContain('from public,anon,authenticated;')
    expect(sql).toContain('grant execute on function public.save_attendance_policy_for_owner_v1(uuid,uuid,text,jsonb,uuid,uuid) to service_role;')
    expect(sql.replace(/--[^\n]*/g,'')).not.toMatch(/grant\s+(?:select|insert|update|all)|create or replace|alter table|insert into|update public\.|delete from|set_config|users\.role|auth\.(?:role|uid)/i)
  })
  it('uses the real operation-before-row order and132 entitlement serialization key before mutation', () => {
    const old = readFileSync('supabase/migrations/132_attendance_teacher_entitlements.sql','utf8')
    const key = old.match(/hashtextextended\(p_teacher_id::text,\s*(\d+)\)/)![1]
    const operation = sql.indexOf('if not public.classroom_purge_try_lock(p_classroom_id)')
    const row = sql.indexOf('where c.id=p_classroom_id for update nowait;')
    const entitlement = sql.indexOf(`pg_catalog.hashtextextended(p_actor_id::text,${key})`)
    const entitlementCheck = sql.indexOf('if not public.attendance_teacher_entitled_v1(')
    const mutation = sql.indexOf('v_result := public.upsert_attendance_timing_policy_v1(')
    expect(operation).toBeGreaterThan(0)
    expect(operation).toBeLessThan(row); expect(row).toBeLessThan(entitlement)
    expect(entitlement).toBeLessThan(entitlementCheck); expect(entitlementCheck).toBeLessThan(mutation)
    expect(sql).toContain('from public.attendance_teacher_entitlements e where e.teacher_id=p_actor_id for share nowait')
    expect(sql).toContain('from public.attendance_roster_mappings r where r.classroom_id=p_classroom_id for share nowait')
    expect(sql).not.toContain('pg_advisory_xact_lock(')
  })
  it('requires current owner, active classroom, every maintenance/lifecycle fence and the stricter writer entitlement', () => {
    expect(sql).toContain('v_classroom.teacher_id is distinct from p_actor_id')
    expect(sql).toContain('v_classroom.archived_at is not null')
    expect(sql).toContain('perform public.guard_classroom_purge_lifecycle(p_classroom_id)')
    for (const flag of ['restore','compaction','pika.identity_mapping','pika.classroom_purge_finalize','pika.course_blueprint_purge_finalize','pika.student_purge_finalize']) expect(sql).toContain(`'${flag}'`)
    expect(sql).toContain("p_canary_actor_id is distinct from p_actor_id or p_canary_classroom_id is distinct from p_classroom_id")
    expect(sql).toContain("r.integration_state <> 'active'")
    const writerGuard = sql.slice(sql.indexOf('if not public.attendance_teacher_entitled_v1('),sql.indexOf('v_result := public.upsert_attendance_timing_policy_v1('))
    expect(writerGuard).toContain('pg_catalog.statement_timestamp()')
    expect(writerGuard).not.toMatch(/when.*exact_canary.*then|p_scope_mode='teacher_entitlements' and/)
  })
  it('binds strict normalized input, original revision behavior and actual row/result postconditions', () => {
    expect(sql).toContain('pg_catalog.jsonb_object_keys(p_policy)) <> 9')
    expect(sql).toContain('(p_policy->>\'entry_opens_minutes_before\')::integer > 120')
    expect(sql).toContain('v_duration <= 0 or v_duration > 720')
    expect(sql).toContain('v_result is distinct from v_expected')
    expect(sql).toContain('v_after.policy_revision is distinct from coalesce(v_before.policy_revision,0)+1')
    expect(sql).toContain('v_after.created_at is distinct from v_before.created_at')
    expect(sql.match(/v_result := public\.upsert_attendance_timing_policy_v1\(/g)).toHaveLength(1)
    expect(sql).not.toMatch(/p_at\s+timestamptz|enqueue_attendance|attendance_principal_mappings|student_profiles/)
  })
  it('translates only known legacy errors and leaves unknown authorization/lifecycle faults unavailable', () => {
    expect(sql).toContain("if sqlstate='40001' and v_message not in ('classroom_operation_busy','attendance_policy_revision_conflict') then raise; end if")
    expect(sql).toContain("if v_message not in ('attendance_policy_invalid','attendance_policy_timing_invalid') then raise; end if")
    expect(sql).toContain("if v_message='attendance_classroom_not_entitled' then")
    expect(sql).toContain("if v_message not in ('classroom_purge_active','attendance_decommission_active') then raise; end if")
    expect(sql).not.toContain('when others')
  })
  it('prepares real service-role create/update/revision/timing/denial cases and complete rollback of trigger side effects', () => {
    for (const stage of ['$catalog$','$unentitled_canary$','$write_matrix$','$complement$','$whole_rollback$']) expect(rollback).toContain(stage)
    expect(rollback).toContain("where n.nspname in ('public','private') and c.relkind in ('r','p')")
    expect(rollback).toContain('jsonb_agg(to_jsonb(r) order by to_jsonb(r)::text)')
    expect(rollback).toContain('rollback to fixture;')
    expect(rollback).toContain('Attendance write fixture whole-row rollback differs')
    expect(rollback).toContain('Policy write changed nonpolicy graph')
    expect(rollback).toContain('Rejected write changed policy rows')
    expect(rollback).toContain('No denied call may mutate it')
    expect(rollback).toContain('Pre-existing synthetic grants only')
    expect(rollback).toContain('missing update revision')
    expect(rollback).toContain('unchanged body still increments once')
    expect(rollback).toContain("valid_until=null,status='revoked'")
    expect(rollback).toContain("'deactivating'"); expect(rollback).toContain("integration_state='inactive'")
    expect(rollback).toMatch(/rollback;\s*select pg_catalog.json_build_object\('version',1,'scope','attendance-policy-write-rollback-contract-v1'/)
    expect(rollback).not.toMatch(/disable\s+trigger|session_replication_role|update\s+private\.\w*settings|insert into public\.attendance_principal_mappings/i)
  })
  it('uses an attendance-free owned class for the real127 hot purge prerequisite', () => {
    const old = readFileSync('supabase/migrations/127_bara_attendance_event_inbox.sql','utf8')
    expect(old).toMatch(/create trigger reject_attendance_classroom_purge_v1\s+before insert on public\.classroom_purge_operations/)
    const block = rollback.split('savepoint hot_fence;')[1].split('rollback to hot_fence;')[0]
    const id = 'e2000000-0000-4000-8000-000000000003'
    expect(block.match(new RegExp(id,'g'))).toHaveLength(3)
    expect(rollback).toContain(`('${id}','e1000000-0000-4000-8000-000000000001','Attendance-free fence'`)
    expect(rollback).not.toMatch(new RegExp(`insert into public\\.attendance_(?:window_policies|roster_mappings)[^;]*${id}`))
  })
})
